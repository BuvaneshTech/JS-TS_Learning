

// this at method is used to find the what value is present at given index


let value = [88,99,44,55,66,88,22]
console.log(value.at(5)); // 88
console.log(value.at(2)); // 44 
console.log(value.at(8)); // undefined

// we should not use value.at[] thgis will return undefined 

// but we can use negative indexing

console.log(value.at[0]); // undefined

console.log(value.at(-2)); // 88 


